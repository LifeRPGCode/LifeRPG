"""
Задача: Трактир "Усталый Путник"

Ты заходишь в трактир. У тебя есть gold = 200 и hp = 80 (максимум hp_max = 100). Трактирщик предлагает меню:
Эль — восстанавливает 15 HP, стоит 30 золотых.
Жареный кабан — восстанавливает 40 HP, стоит 80 золотых.
Комната отдыха — полностью восстанавливает HP (до максимума), стоит 150 золотых.
Напиши программу, которая делает следующее:

Шаг 1. Выводит текущий статус игрока (золото и здоровье с полоской, как ты умеешь).

Шаг 2. Предлагает меню:
Меню трактира:
1. Эль (30 золота, +15 HP)
2. Жареный кабан (80 золота, +40 HP)
3. Комната отдыха (150 золота, полное восстановление HP)
4. Уйти

Шаг 3. Спрашивает "Что выбираешь? (1-4): ".

Шаг 4. Обрабатывает выбор (без циклов, просто if/elif/else):
Если выбрал 1, 2 или 3 — проверяет, хватает ли золота.
Если хватает → списывает золото, восстанавливает HP (не превышая максимум!), выводит сообщение об успехе.
Если не хватает → выводит "Недостаточно золота, бродяга!"
Если выбрал 4 → выводит "Ты покидаешь трактир."
Если введено что-то другое → выводит "Такого блюда нет в меню."

Шаг 5. После всех действий выводит обновлённый статус игрока (золото и здоровье с полоской), кроме случая "Уйти" — там просто прощание.
"""

gold = 200
hp_max = 100
hp = 40
current_hp_percent = hp / hp_max * 100
full = round(current_hp_percent / 10)
empty = 10 - full
bars = "█" * full + "░" * empty
item_1 = '1 - [Эль (30 золота, +15 HP)]'
item_2 = '2 - [Жареный кабан (80 золота, +40 HP)]'
item_3 = '3 - [Комната отдыха (150 золота, полное восстановление HP)]'
item_4 = '4 - [Уйти]'
print("Добро пожаловать в таверну Усталый Путник. Трактирщик обращает на тебя внимание, подзывает к себе и спрашивает: \nХочешь взглянуть на меню?")
menu_open = input("Взглянуть на меню? да/нет ")
if menu_open == "да":
    print(f"Меню трактира Усталый Путник: \n{item_1} \n{item_2} \n{item_3} \n{item_4}")
    menu_1 = input("Выбирай что хочешь купить (Введи 1-4): ")
    if menu_1 == "1":
        if gold >= 30:
            hp += 15
            hp = min(hp, hp_max)
            current_hp_percent = hp / hp_max * 100
            full = round(current_hp_percent / 10)
            empty = 10 - full
            bars = "█" * full + "░" * empty
            gold -= 30
            print(f"Куплено: Эль. Здоровье: [{bars}] {hp}/{hp_max}. Золото: {gold}")
        else:
            print("Недостаточно золота. Золото:", gold)
    elif menu_1 == "2":
        if gold >= 80:
            hp += 40
            hp = min(hp, hp_max)
            current_hp_percent = hp / hp_max * 100
            full = round(current_hp_percent / 10)
            empty = 10 - full
            bars = "█" * full + "░" * empty
            gold -= 80
            print(f"Куплено: Жареный кабан. Здоровье: [{bars}] {hp}/{hp_max}. Золото: {gold}")
        else:
            print("Недостаточно золота. Золото:", gold)
    elif menu_1 == "3":
        if gold >= 150:
            hp = hp_max
            current_hp_percent = hp / hp_max * 100
            full = round(current_hp_percent / 10)
            empty = 10 - full
            bars = "█" * full + "░" * empty
            gold -= 150
            print(f"Куплено: Комната отдыха. Здоровье: [{bars}] {hp}/{hp_max}. Золото: {gold}")
        else:
            print("Недостаточно золота. Золото:", gold)
    elif menu_1 == "4":
        print("Всего доброго! (Вы вышли с таверны)")
    else:
        print("Такого нет в меню")
elif menu_open == "нет":
    print("Хорошо, тогда удачи в путешествии!")
else:
    print("Неизвестная команда, надо выбрать да/нет")
